class OfertaLaboral{
    constructor(id, titulo, empresa, descripcion, nivelRequerido, area, limitePostulaciones, vacantes, destacada, estado){
        this.id = id
        this.titulo = titulo
        this.empresa = empresa
        this.descripcion = descripcion
        this.nivelRequerido = nivelRequerido
        this.area = area
        this.limitePostulaciones = limitePostulaciones
        this.vacantes = vacantes
        this.destacada = destacada
        this.estado = estado
    }
}